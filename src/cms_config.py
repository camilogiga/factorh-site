"""Writes .pages.yml, the form layout of the Pages CMS editor (https://app.pagescms.org).

Every text in content/*.yml becomes a field labelled with its kind and the start of its current
text, and every photo becomes an image picker. Run it again whenever a template gains or loses
a text: python3 src/cms_config.py
"""
import re, pathlib, yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGES = [("index", "Inicio"), ("servicios", "Servicios"), ("como-trabajamos", "Cómo trabajamos"),
         ("nosotros", "Nosotros"), ("contacto", "Contacto"), ("politica-datos", "Política de datos"),
         ("404", "Página no encontrada"), ("site", "Menú, pie de página y correo (todas las páginas)")]
KIND = {"h1": "Título", "h2": "Título de sección", "h3": "Subtítulo", "h4": "Subtítulo", "p": "Texto",
        "a": "Botón o enlace", "li": "Elemento de lista", "span": "Texto", "strong": "Texto en negrita",
        "label": "Campo del formulario", "button": "Botón", "option": "Opción de la lista", "figcaption": "Pie de foto",
        "blockquote": "Cita", "texto": "Texto", "alt": "Descripción de la foto (Google y lectores de pantalla)",
        "aria": "Nombre para lectores de pantalla", "placeholder": "Ayuda dentro del campo", "title": "Texto al pasar el mouse",
        "titulo": "Título en la pestaña y en Google", "descripcion": "Descripción en Google y al compartir",
        "correo": "Correo de contacto (enlaces y destino del formulario)"}
GROUPS = {"google": "Google y pestaña del navegador", "menu": "Menú superior", "pie": "Pie de página", "datos": "Datos de contacto"}

def preview(v, n=60):
    v = re.sub(r"\*\*|\[\[|\]\]|(?<!\w)_|_(?!\w)", "", str(v)).replace("\n", " ").strip()
    return v if len(v) <= n else v[:n].rsplit(" ", 1)[0] + "…"

def field(key, value):
    kind = key.split("_")[0]
    if kind == "foto":
        return {"name": key, "label": "Foto: " + str(value).rsplit("/", 1)[-1], "type": "image"}
    t = "text" if "\n" in str(value) or len(str(value)) > 70 else "string"
    return {"name": key, "label": f"{KIND.get(kind, 'Texto')}: {preview(value)}", "type": t}

def group_label(g, items):
    if g in GROUPS: return GROUPS[g]
    head = next((v for k, v in items.items() if k.split("_")[0] in ("h1", "h2")), None)
    head = head or next((v for k, v in items.items() if k.split("_")[0] not in ("foto", "alt", "aria") and len(str(v)) > 3), None)
    return "Sección: " + preview(head, 50) if head else g.replace("_", " ").capitalize()

content = []
for name, label in PAGES:
    data = yaml.safe_load((ROOT / "content" / f"{name}.yml").read_text(encoding="utf-8"))
    groups = [{"name": g, "label": group_label(g, items), "type": "object", "fields": [field(k, v) for k, v in items.items()]}
              for g, items in data.items()]
    content.append({"name": name, "label": label, "type": "file", "path": f"content/{name}.yml", "fields": groups})

config = {"media": {"input": "static/img", "output": "img"}, "content": content}
header = "# Generated by src/cms_config.py. Edit content/*.yml or the templates, not this file.\n"
(ROOT / ".pages.yml").write_text(header + yaml.dump(config, allow_unicode=True, sort_keys=False, width=1000), encoding="utf-8")
print("wrote .pages.yml")
